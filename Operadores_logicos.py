# Trabalham com dados do tipo Boolean.
# Vai analisar uma sequência e retornam apenas true ou false.

# Operadores:
# Maior(>), maior igual(>=), menor(<), menor igual(<=), igualdade(=) e diferente(!=)

a = 8
b = 2

# Maior
print(8>2)

# Maior igual
print(8>=2)

# Menor
print(8<=2)

# Menor igual
print(8>=2)

# igualdade
print(8==2)

# Vale lembrar que = - recebe/ == - igualdade

# Diferente
print(8!=2)