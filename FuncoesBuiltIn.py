# Abs
# Retorna o valor absoluto do número
print(abs(-10))   # Resultado: 10

# Min
# Retorna o valor mínimo de uma sequência
print(min(6, 2, 7, 3, 1, 7))   # Resultado: 1


# Max
# Retorna o valor máximo de uma sequência
print(max(6, 2, 7, 3, 1)) # Resultado: 7

# Sum
# Faz a soma dos valores de uma sequência
somaTotal = sum([1,2,3,4])
print(somaTotal)

# Pow
# Faz o cálculo de exponenciação
print(pow(2,3))

# Print
# Mostra o valor de saída na tela
print("Olá mundo")

# Input
# Lê o valor digitado no terminal pelo usuário
nome=input('Qual é o seu nome? ')
print(nome)

